function loadFontFace(module: any, data: any) {
  const { fontFamily, url } = data
  return fetch(url)
    .then((res) => res.arrayBuffer())
    .then((res) => new Uint8Array(res))
    .then((res) => {
      const dataPtr = module._malloc(res.length)
      const dataOnHeap = new Uint8Array(module.HEAPU8.buffer, dataPtr, res.length)
      dataOnHeap.set(res)
      module._registerFallbackFont(dataPtr, res.length, fontFamily)
      console.log("------")
      return res
    })
}
