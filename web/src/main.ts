function updateImage(CanvasKit: any, imageLayer: any) {
  return new Promise<void>((resolve, reject) => {
    const img = document.createElement('img')
    img.crossOrigin = 'Anonymous'
    const url = imageLayer._getLayerImagePath()
    console.log('url: ', url)
    img.src = url
    img.onload = () => {
      const nativeImage = new NativeImage(img)
      const imageData = nativeImage.getImageData()
      const numBytes = imageData.data?.byteLength
      const dataPtr = CanvasKit._malloc(numBytes)
      const dataOnHeap = new Uint8Array(CanvasKit.HEAPU8.buffer, dataPtr, numBytes)
      dataOnHeap.set(imageData.data)
      imageLayer._updateLayerImage(dataPtr, nativeImage.width(), nativeImage.height(), 4)
      resolve()
    }
    img.onerror = () => {
      reject()
    }
  })
}

